using System.Collections.Generic;
using UnityEditor;
using UnityEngine;
using jp.lilxyzw.lilycalinventory.runtime;
using Migimaru.OnOffMenuItemSetupSupporter;

namespace Migimaru.OnOffMenuItemSetupSupporter.Editor
{
    public enum ItemTogglerSetupMode
    {
        HideWhenOn,
        HideWhenOff
    }

    // Existing generation helpers remain here; both public entry points use the shared workspace.
    public sealed class ItemTogglerSetupWindow : EditorWindow
    {
        private enum ChildFolderPosition
        {
            Top,
            Bottom
        }

        private sealed class MeshEntry
        {
            public GameObject gameObject;
            // null = 登録しない
            public GameObject selectedMenuFolder;
        }

        private sealed class OutfitEntry
        {
            public GameObject root = null;
            public readonly List<MeshEntry> meshObjects = new List<MeshEntry>();
        }

        private sealed class MenuFolderEntry
        {
            public GameObject gameObject;
            public string displayName;
        }

        private sealed class SelectionGroup
        {
            public GameObject menuFolder;
            public readonly List<GameObject> meshes = new List<GameObject>();
        }

        private GameObject sourceMenuFolder = null;
        private ItemTogglerSetupMode setupMode = ItemTogglerSetupMode.HideWhenOn;
        private readonly List<OutfitEntry> outfits = new List<OutfitEntry>
        {
            new OutfitEntry()
        };
        private readonly List<MenuFolderEntry> menuFolders = new List<MenuFolderEntry>();
        private bool skipEditorOnlyMenuCreation = true;
        private bool autoAdjustToEightItems = true;
        private ChildFolderPosition childFolderPosition = ChildFolderPosition.Top;
        public static void Open(GameObject sourceMenuFolder, ItemTogglerSetupMode setupMode)
        {
            ItemTogglerEditWindow.OpenWorkspace(sourceMenuFolder, setupMode, true);
        }

        internal static bool CanEnableAddButton(int selectedItemCount, bool autoAdjustEnabled, bool canUseAutoAdjust)
        {
            if (selectedItemCount <= 0)
            {
                return false;
            }

            if (autoAdjustEnabled && !canUseAutoAdjust)
            {
                return false;
            }

            return true;
        }

        private static int CountSelectedItems(List<SelectionGroup> groups)
        {
            int result = 0;
            foreach (SelectionGroup group in groups)
            {
                result += group.meshes.Count;
            }

            return result;
        }

        private void AddItemTogglers()
        {
            if (sourceMenuFolder == null)
            {
                return;
            }

            if (CountSelectedItems(CollectSelectionGroups()) <= 0)
            {
                return;
            }

            Undo.IncrementCurrentGroup();
            int undoGroup = Undo.GetCurrentGroup();
            Undo.SetCurrentGroupName("ItemTogglerを追加");
            CreateSelectedItemTogglers();
            ApplyChildFolderOrderToAll();
            Undo.CollapseUndoOperations(undoGroup);
            Close();
        }

        private void OverwriteItemTogglers()
        {
            if (sourceMenuFolder == null)
            {
                return;
            }

            Undo.IncrementCurrentGroup();
            int undoGroup = Undo.GetCurrentGroup();
            Undo.SetCurrentGroupName("ItemTogglerを上書き");
            DeleteExistingItemTogglers();
            DeleteAutoGeneratedNextPages();
            CreateSelectedItemTogglers();
            ApplyChildFolderOrderToAll();
            Undo.CollapseUndoOperations(undoGroup);
            Close();
        }

        private void CreateSelectedItemTogglers()
        {
            List<SelectionGroup> groups = CollectSelectionGroups();
            foreach (SelectionGroup group in groups)
            {
                if (autoAdjustToEightItems)
                {
                    CreateItemsWithPagination(group.menuFolder, group.meshes);
                }
                else
                {
                    foreach (GameObject meshObject in group.meshes)
                    {
                        CreateItemToggler(meshObject, group.menuFolder);
                    }
                }
            }
        }

        private List<SelectionGroup> CollectSelectionGroups()
        {
            List<SelectionGroup> groups = new List<SelectionGroup>();
            Dictionary<GameObject, SelectionGroup> lookup = new Dictionary<GameObject, SelectionGroup>();
            HashSet<GameObject> collectedMeshes = new HashSet<GameObject>();
            foreach (OutfitEntry outfit in outfits)
            {
                foreach (MeshEntry meshEntry in outfit.meshObjects)
                {
                    if (meshEntry.gameObject == null || meshEntry.selectedMenuFolder == null)
                    {
                        continue;
                    }

                    if (skipEditorOnlyMenuCreation && IsEffectivelyEditorOnly(meshEntry.gameObject))
                    {
                        continue;
                    }

                    if (!IsSelectableMenuFolder(meshEntry.selectedMenuFolder))
                    {
                        continue;
                    }

                    if (!collectedMeshes.Add(meshEntry.gameObject))
                    {
                        continue;
                    }

                    GameObject targetFolder = meshEntry.selectedMenuFolder;
                    SelectionGroup group;
                    if (!lookup.TryGetValue(targetFolder, out group))
                    {
                        group = new SelectionGroup
                        {
                            menuFolder = targetFolder
                        };
                        lookup.Add(targetFolder, group);
                        groups.Add(group);
                    }

                    group.meshes.Add(meshEntry.gameObject);
                }
            }

            return groups;
        }

        private void CreateItemsWithPagination(GameObject targetMenuFolder, List<GameObject> meshes)
        {
            if (targetMenuFolder == null || meshes == null || meshes.Count == 0)
            {
                return;
            }

            GameObject currentPage = targetMenuFolder;
            int meshIndex = 0;
            while (meshIndex < meshes.Count)
            {
                GameObject existingNextPage = GetDirectAutoNextPage(currentPage);
                int childFolderCount = CountDirectManualChildMenuFolders(currentPage);
                int existingItemCount = CountDirectItemTogglers(currentPage);
                if (existingNextPage != null)
                {
                    int availableSlots = MenuPageCalculator.GetAvailableItemSlots(childFolderCount, existingItemCount, true);
                    while (availableSlots > 0 && meshIndex < meshes.Count)
                    {
                        CreateItemToggler(meshes[meshIndex], currentPage);
                        meshIndex++;
                        availableSlots--;
                    }

                    currentPage = existingNextPage;
                    continue;
                }

                int remaining = meshes.Count - meshIndex;
                int availableWithoutNextPage = MenuPageCalculator.GetAvailableItemSlots(childFolderCount, existingItemCount, false);
                if (remaining <= availableWithoutNextPage)
                {
                    while (meshIndex < meshes.Count)
                    {
                        CreateItemToggler(meshes[meshIndex], currentPage);
                        meshIndex++;
                    }

                    break;
                }

                int availableWithNextPage = MenuPageCalculator.GetAvailableItemSlots(childFolderCount, existingItemCount, true);
                if (availableWithNextPage < 0)
                {
                    Debug.LogWarning("8項目以内に自動調整できません。");
                    return;
                }

                for (int i = 0; i < availableWithNextPage && meshIndex < meshes.Count; i++)
                {
                    CreateItemToggler(meshes[meshIndex], currentPage);
                    meshIndex++;
                }

                currentPage = CreateAutoNextPage(currentPage);
            }
        }

        private GameObject CreateAutoNextPage(GameObject parentMenuFolder)
        {
            string nextPageName = FindAvailableNextPageName(parentMenuFolder);
            GameObject nextPage = new GameObject(nextPageName);
            Undo.RegisterCreatedObjectUndo(nextPage, "NextPageを作成");
            Undo.SetTransformParent(nextPage.transform, parentMenuFolder.transform, "NextPageを配置");
            nextPage.transform.localPosition = Vector3.zero;
            nextPage.transform.localRotation = Quaternion.identity;
            nextPage.transform.localScale = Vector3.one;
            MenuFolder menuFolder = Undo.AddComponent<MenuFolder>(nextPage);
            SerializedObject serializedObject = new SerializedObject(menuFolder);
            SerializedProperty menuName = serializedObject.FindProperty("menuName");
            if (menuName != null)
            {
                menuName.stringValue = nextPageName;
                serializedObject.ApplyModifiedProperties();
            }

            Undo.AddComponent<AutoGeneratedNextPageMarker>(nextPage);
            return nextPage;
        }

        private static string FindAvailableNextPageName(GameObject parentMenuFolder)
        {
            int number = 1;
            while (true)
            {
                string targetName = number == 1 ? "NextPage" : $"NextPage{number}";
                bool exists = false;
                foreach (Transform child in parentMenuFolder.transform)
                {
                    if (child.name == targetName)
                    {
                        exists = true;
                        break;
                    }
                }

                if (!exists)
                {
                    return targetName;
                }

                number++;
            }
        }

        private static GameObject GetDirectAutoNextPage(GameObject parent)
        {
            foreach (Transform child in parent.transform)
            {
                if (child.GetComponent<MenuFolder>() == null)
                {
                    continue;
                }

                if (child.GetComponent<AutoGeneratedNextPageMarker>() == null)
                {
                    continue;
                }

                return child.gameObject;
            }

            return null;
        }

        private static int CountDirectItemTogglers(GameObject parent)
        {
            int count = 0;
            foreach (Transform child in parent.transform)
            {
                if (child.GetComponent<ItemToggler>() != null)
                {
                    count++;
                }
            }

            return count;
        }

        private static int CountDirectManualChildMenuFolders(GameObject parent)
        {
            int count = 0;
            foreach (Transform child in parent.transform)
            {
                if (child.GetComponent<MenuFolder>() == null)
                {
                    continue;
                }

                if (child.GetComponent<AutoGeneratedNextPageMarker>() != null)
                {
                    continue;
                }

                count++;
            }

            return count;
        }

        // Child ordering
        private void ApplyChildFolderOrderToAll()
        {
            if (sourceMenuFolder == null)
            {
                return;
            }

            MenuFolder[] folders = sourceMenuFolder.GetComponentsInChildren<MenuFolder>(true);
            foreach (MenuFolder folder in folders)
            {
                if (folder.GetComponent<AutoGeneratedNextPageMarker>() != null)
                {
                    continue;
                }

                ApplyChildFolderOrder(folder.gameObject);
            }
        }

        private void ApplyChildFolderOrder(GameObject parent)
        {
            List<Transform> manualFolders = new List<Transform>();
            List<Transform> itemTogglers = new List<Transform>();
            List<Transform> nextPages = new List<Transform>();
            foreach (Transform child in parent.transform)
            {
                if (child.GetComponent<AutoGeneratedNextPageMarker>() != null && child.GetComponent<MenuFolder>() != null)
                {
                    nextPages.Add(child);
                    continue;
                }

                if (child.GetComponent<MenuFolder>() != null)
                {
                    manualFolders.Add(child);
                    continue;
                }

                if (child.GetComponent<ItemToggler>() != null)
                {
                    itemTogglers.Add(child);
                }
            }

            int siblingIndex = 0;
            if (childFolderPosition == ChildFolderPosition.Top)
            {
                foreach (Transform folder in manualFolders)
                {
                    folder.SetSiblingIndex(siblingIndex++);
                }

                foreach (Transform item in itemTogglers)
                {
                    item.SetSiblingIndex(siblingIndex++);
                }
            }
            else
            {
                foreach (Transform item in itemTogglers)
                {
                    item.SetSiblingIndex(siblingIndex++);
                }

                foreach (Transform folder in manualFolders)
                {
                    folder.SetSiblingIndex(siblingIndex++);
                }
            }

            foreach (Transform nextPage in nextPages)
            {
                nextPage.SetAsLastSibling();
            }
        }

        // Deletion
        private void DeleteExistingItemTogglers()
        {
            ItemToggler[] itemTogglers = sourceMenuFolder.GetComponentsInChildren<ItemToggler>(true);
            foreach (ItemToggler itemToggler in itemTogglers)
            {
                if (itemToggler == null)
                {
                    continue;
                }

                if (CanDeleteItemTogglerGameObject(itemToggler))
                {
                    Undo.DestroyObjectImmediate(itemToggler.gameObject);
                }
                else
                {
                    Undo.DestroyObjectImmediate(itemToggler);
                }
            }
        }

        private static bool CanDeleteItemTogglerGameObject(ItemToggler itemToggler)
        {
            if (itemToggler == null)
            {
                return false;
            }

            GameObject targetObject = itemToggler.gameObject;
            if (targetObject == null || targetObject.transform.childCount > 0)
            {
                return false;
            }

            Component[] components = targetObject.GetComponents<Component>();
            foreach (Component component in components)
            {
                if (component == null)
                {
                    return false;
                }

                if (component is Transform || component == itemToggler)
                {
                    continue;
                }

                return false;
            }

            return true;
        }

        private void DeleteAutoGeneratedNextPages()
        {
            AutoGeneratedNextPageMarker[] markers = sourceMenuFolder.GetComponentsInChildren<AutoGeneratedNextPageMarker>(true);
            foreach (AutoGeneratedNextPageMarker marker in markers)
            {
                if (marker == null)
                {
                    continue;
                }

                Undo.DestroyObjectImmediate(marker.gameObject);
            }
        }

        // ItemToggler
        private void CreateItemToggler(GameObject meshObject, GameObject targetMenuFolder)
        {
            GameObject togglerObject = new GameObject(meshObject.name);
            Undo.RegisterCreatedObjectUndo(togglerObject, "ItemTogglerを作成");
            Undo.SetTransformParent(togglerObject.transform, targetMenuFolder.transform, "ItemTogglerを配置");
            togglerObject.transform.localPosition = Vector3.zero;
            togglerObject.transform.localRotation = Quaternion.identity;
            togglerObject.transform.localScale = Vector3.one;
            ItemToggler itemToggler = Undo.AddComponent<ItemToggler>(togglerObject);
            SerializedObject serializedObject = new SerializedObject(itemToggler);
            /*
             * menuNameは設定しない。
             *
             * lilycalInventory側ではmenuNameが空の場合、
             * GameObject.nameがメニュー名として使用される。
             *
             * これによりHierarchyでGameObject名を変更した際に、
             * メニュー名も追従する。
             */
            bool initiallyActive = meshObject.activeSelf;
            SerializedProperty defaultValue = serializedObject.FindProperty("defaultValue");
            if (initiallyActive)
            {
                defaultValue.boolValue = setupMode == ItemTogglerSetupMode.HideWhenOff;
            }
            else
            {
                defaultValue.boolValue = setupMode == ItemTogglerSetupMode.HideWhenOn;
            }

            SerializedProperty parameter = serializedObject.FindProperty("parameter");
            SerializedProperty objects = parameter.FindPropertyRelative("objects");
            objects.arraySize = 1;
            SerializedProperty element = objects.GetArrayElementAtIndex(0);
            SerializedProperty objectProperty = element.FindPropertyRelative("obj");
            SerializedProperty valueProperty = element.FindPropertyRelative("value");
            objectProperty.objectReferenceValue = meshObject;
            valueProperty.boolValue = !initiallyActive;
            serializedObject.ApplyModifiedProperties();
        }

        private void RefreshAllMeshLists()
        {
            Dictionary<GameObject, GameObject> previousSelections = new Dictionary<GameObject, GameObject>();
            foreach (OutfitEntry outfit in outfits)
            {
                foreach (MeshEntry meshEntry in outfit.meshObjects)
                {
                    if (meshEntry.gameObject == null || previousSelections.ContainsKey(meshEntry.gameObject))
                    {
                        continue;
                    }

                    previousSelections.Add(meshEntry.gameObject, meshEntry.selectedMenuFolder);
                }
            }

            List<GameObject> roots = new List<GameObject>();
            foreach (OutfitEntry outfit in outfits)
            {
                roots.Add(outfit.root);
            }

            List<List<GameObject>> uniqueMeshLists = BuildUniqueMeshLists(roots);
            for (int i = 0; i < outfits.Count; i++)
            {
                OutfitEntry outfit = outfits[i];
                outfit.meshObjects.Clear();
                foreach (GameObject meshObject in uniqueMeshLists[i])
                {
                    GameObject selected = null;
                    previousSelections.TryGetValue(meshObject, out selected);
                    outfit.meshObjects.Add(new MeshEntry { gameObject = meshObject, selectedMenuFolder = selected });
                }
            }
        }

        internal static List<List<GameObject>> BuildUniqueMeshLists(IList<GameObject> roots)
        {
            List<List<GameObject>> result = new List<List<GameObject>>();
            HashSet<GameObject> seenMeshes = new HashSet<GameObject>();
            foreach (GameObject root in roots)
            {
                List<GameObject> meshes = new List<GameObject>();
                result.Add(meshes);
                if (root == null)
                {
                    continue;
                }

                Transform[] transforms = root.GetComponentsInChildren<Transform>(true);
                foreach (Transform targetTransform in transforms)
                {
                    GameObject targetObject = targetTransform.gameObject;
                    if (!HasMesh(targetObject))
                    {
                        continue;
                    }

                    if (!seenMeshes.Add(targetObject))
                    {
                        continue;
                    }

                    meshes.Add(targetObject);
                }
            }

            return result;
        }

        private static bool HasMesh(GameObject targetObject)
        {
            if (targetObject.GetComponent<SkinnedMeshRenderer>() != null)
            {
                return true;
            }

            MeshRenderer meshRenderer = targetObject.GetComponent<MeshRenderer>();
            MeshFilter meshFilter = targetObject.GetComponent<MeshFilter>();
            return meshRenderer != null && meshFilter != null;
        }

        private void RefreshMenuFolderList()
        {
            menuFolders.Clear();
            if (sourceMenuFolder == null)
            {
                return;
            }

            MenuFolder[] foundFolders = sourceMenuFolder.GetComponentsInChildren<MenuFolder>(true);
            Dictionary<string, int> nameCounts = new Dictionary<string, int>();
            foreach (MenuFolder folder in foundFolders)
            {
                if (folder == null || folder.GetComponent<AutoGeneratedNextPageMarker>() != null)
                {
                    continue;
                }

                string name = folder.gameObject.name;
                if (nameCounts.ContainsKey(name))
                {
                    nameCounts[name]++;
                }
                else
                {
                    nameCounts[name] = 1;
                }
            }

            foreach (MenuFolder folder in foundFolders)
            {
                if (folder == null || folder.GetComponent<AutoGeneratedNextPageMarker>() != null)
                {
                    continue;
                }

                GameObject folderObject = folder.gameObject;
                string displayName;
                if (folderObject == sourceMenuFolder)
                {
                    displayName = folderObject.name;
                }
                else if (nameCounts[folderObject.name] > 1)
                {
                    displayName = GetRelativePath(sourceMenuFolder.transform, folderObject.transform);
                }
                else
                {
                    displayName = folderObject.name;
                }

                menuFolders.Add(new MenuFolderEntry { gameObject = folderObject, displayName = displayName });
            }
        }

        private static string GetRelativePath(Transform root, Transform target)
        {
            Stack<string> names = new Stack<string>();
            Transform current = target;
            while (current != null && current != root)
            {
                names.Push(current.name);
                current = current.parent;
            }

            return string.Join("/", names);
        }

        internal static bool IsSelectableMenuFolder(GameObject menuFolder)
        {
            if (menuFolder == null)
            {
                return false;
            }

            if (menuFolder.GetComponent<MenuFolder>() == null)
            {
                return false;
            }

            return !IsEffectivelyEditorOnly(menuFolder);
        }

        private static bool IsEffectivelyEditorOnly(GameObject targetObject)
        {
            if (targetObject == null)
            {
                return false;
            }

            if (targetObject.CompareTag("EditorOnly"))
            {
                return true;
            }

            return HasEditorOnlyAncestor(targetObject);
        }

        private static bool HasEditorOnlyAncestor(GameObject targetObject)
        {
            if (targetObject == null)
            {
                return false;
            }

            Transform current = targetObject.transform.parent;
            while (current != null)
            {
                if (current.CompareTag("EditorOnly"))
                {
                    return true;
                }

                current = current.parent;
            }

            return false;
        }
    }
