    public sealed partial class ItemTogglerEditWindow
    {
        private void RebuildFromHierarchy()
        {
            if (sceneHistory == null && sourceMenuFolder != null)
                sceneHistory = new MenuSceneHistory(sourceMenuFolder);
            initialized = false;
            menuFolders.Clear();
            existingGroups.Clear();
            displayEntries.Clear();
            statusMessages.Clear();
            if (sourceMenuFolder == null)
                return;
            BuildMenuFolderList();
            BuildGlobalTargetRegistrationMap();
            if (!overwriteMode)
            {
                foreach (var toggler in GetRelevantItemTogglers())
                {
                    var group = BuildExistingGroup(toggler);
                    existingGroups.Add(group);
                    displayEntries.AddRange(group.entries);
                    if (group.entries.Count == 0)
                        statusMessages.Add(toggler.name + ": Object Targetがないため構造を維持します。");
                    foreach (var entry in group.entries)
                    {
                        var root = FindOutfitRoot(entry.gameObject);
                        entry.outfitRoot = root;
                        if (root != null && !outfitRoots.Contains(root))
                            outfitRoots.Add(root);
                    }
                }
            }

            foreach (var root in outfitRoots.ToArray())
                AddMeshesFromRoot(root);
            SortEntriesByOutfit();
            initialized = true;
            Repaint();
        }

        private void BuildMenuFolderList()
        {
            MenuFolder[] found = sourceMenuFolder.GetComponentsInChildren<MenuFolder>(true);
            Dictionary<string, int> nameCounts = new Dictionary<string, int>();
            foreach (MenuFolder folder in found)
            {
                if (folder == null || folder.GetComponent<AutoGeneratedNextPageMarker>() != null)
                {
                    continue;
                }

                string name = folder.gameObject.name;
                if (nameCounts.ContainsKey(name))
                {
                    nameCounts[name]++;
                }
                else
                {
                    nameCounts[name] = 1;
                }
            }

            foreach (MenuFolder folder in found)
            {
                if (folder == null || folder.GetComponent<AutoGeneratedNextPageMarker>() != null)
                {
                    continue;
                }

                GameObject go = folder.gameObject;
                string displayName;
                if (go == sourceMenuFolder)
                {
                    displayName = go.name;
                }
                else if (nameCounts[go.name] > 1)
                {
                    displayName = GetRelativePath(sourceMenuFolder.transform, go.transform);
                }
                else
                {
                    displayName = go.name;
                }

                menuFolders.Add(new MenuFolderEntry { gameObject = go, displayName = displayName });
            }
        }

        private void BuildGlobalTargetRegistrationMap()
        {
            allTargetRegistrations = new Dictionary<GameObject, List<ItemToggler>>();
            GameObject avatarRoot = GetAvatarRootObject();
            if (avatarRoot == null)
            {
                return;
            }

            ItemToggler[] togglers = avatarRoot.GetComponentsInChildren<ItemToggler>(true);
            foreach (ItemToggler toggler in togglers)
            {
                List<GameObject> targets = ReadTargets(toggler);
                foreach (GameObject target in targets)
                {
                    if (target == null)
                    {
                        continue;
                    }

                    List<ItemToggler> list;
                    if (!allTargetRegistrations.TryGetValue(target, out list))
                    {
                        list = new List<ItemToggler>();
                        allTargetRegistrations.Add(target, list);
                    }

                    list.Add(toggler);
                }
            }
        }

        private List<ItemToggler> GetRelevantItemTogglers()
        {
            List<ItemToggler> result = new List<ItemToggler>();
            ItemToggler[] candidates = sourceMenuFolder.GetComponentsInChildren<ItemToggler>(true);
            foreach (ItemToggler toggler in candidates)
            {
                GameObject logicalFolder = ResolveLogicalMenuFolder(toggler);
                if (!IsLogicalFolderInScope(logicalFolder))
                {
                    continue;
                }

                result.Add(toggler);
            }

            return result;
        }

        private ExistingGroup BuildExistingGroup(ItemToggler toggler)
        {
            ExistingGroup group = new ExistingGroup();
            group.toggler = toggler;
            group.logicalMenuFolder = ResolveLogicalMenuFolder(toggler);
            group.originalParent = toggler.transform.parent;
            group.originalSiblingIndex = toggler.transform.GetSiblingIndex();
            SerializedObject serializedObject = new SerializedObject(toggler);
            serializedObject.Update();
            SerializedProperty defaultValue = serializedObject.FindProperty("defaultValue");
            group.originalDefaultValue = defaultValue != null && defaultValue.boolValue;
            group.isSave = ReadBoolProperty(serializedObject, "isSave", true);
            group.isLocalOnly = ReadBoolProperty(serializedObject, "isLocalOnly", false);
            group.autoFixDuplicate = ReadBoolProperty(serializedObject, "autoFixDuplicate", true);
            SerializedProperty icon = serializedObject.FindProperty("icon");
            if (icon != null)
            {
                group.icon = icon.objectReferenceValue as Texture2D;
            }

            SerializedProperty parameter = serializedObject.FindProperty("parameter");
            SerializedProperty objects = parameter.FindPropertyRelative("objects");
            for (int i = 0; i < objects.arraySize; i++)
            {
                SerializedProperty element = objects.GetArrayElementAtIndex(i);
                GameObject target = element.FindPropertyRelative("obj").objectReferenceValue as GameObject;
                if (target == null)
                {
                    continue;
                }

                bool value = element.FindPropertyRelative("value").boolValue;
                EditMeshEntry entry = new EditMeshEntry();
                entry.gameObject = target;
                entry.group = group;
                entry.objectIndex = i;
                entry.originalObjectValue = value;
                entry.existingMode = group.originalDefaultValue == value ? ItemTogglerSetupMode.HideWhenOn : ItemTogglerSetupMode.HideWhenOff;
                entry.selectedMenuFolder = group.logicalMenuFolder;
                entry.snapshotMenuFolder = group.logicalMenuFolder;
                InitializeObjectSnapshot(entry);
                List<ItemToggler> registrations;
                if (allTargetRegistrations.TryGetValue(target, out registrations) && registrations.Count > 1)
                {
                    entry.duplicateRegistration = true;
                    AddLockReason(group, "同じTargetが複数のItemTogglerに登録されています。");
                }

                group.entries.Add(entry);
            }

            if (HasNonObjectParameterSettings(serializedObject))
            {
                AddLockReason(group, "Object Target以外の設定も含まれているため、" + "MenuFolder変更・登録解除・分割は無効です。");
            }

            if (HasMenuParentOverride(serializedObject))
            {
                AddLockReason(group, "MenuFolder Override / Modular Avatar指定があるため、" + "構造編集は無効です。");
            }

            if (group.logicalMenuFolder == null || !ContainsMenuFolder(group.logicalMenuFolder))
            {
                AddLockReason(group, "現在の登録先MenuFolderを安全に再現できないため、" + "構造編集は無効です。");
            }

            return group;
        }

        private EditMeshEntry CreateUnregisteredEntry(GameObject mesh)
        {
            EditMeshEntry entry = new EditMeshEntry();
            entry.gameObject = mesh;
            entry.selectedMenuFolder = null;
            entry.snapshotMenuFolder = null;
            InitializeObjectSnapshot(entry);
            return entry;
        }

        private static void InitializeObjectSnapshot(EditMeshEntry entry)
        {
            if (entry.gameObject == null)
            {
                return;
            }

            entry.snapshotActive = entry.gameObject.activeSelf;
            entry.snapshotTag = entry.gameObject.tag;
            entry.lastNonEditorOnlyTag = entry.gameObject.CompareTag("EditorOnly") ? "Untagged" : entry.gameObject.tag;
        }

        private bool IsLogicalFolderInScope(GameObject folder)
        {
            if (folder == null)
            {
                return false;
            }

            if (folder == sourceMenuFolder)
            {
                return true;
            }

            if (!includeChildMenuFolders)
            {
                return false;
            }

            return folder.transform.IsChildOf(sourceMenuFolder.transform);
        }

        private GameObject ResolveLogicalMenuFolder(ItemToggler toggler)
        {
            if (toggler == null)
            {
                return null;
            }

            SerializedObject serializedObject = new SerializedObject(toggler);
            SerializedProperty parentOverride = serializedObject.FindProperty("parentOverride");
            if (parentOverride != null && parentOverride.objectReferenceValue != null)
            {
                MenuFolder folder = parentOverride.objectReferenceValue as MenuFolder;
                if (folder != null)
                {
                    var currentFolder = folder.transform;
                    while (currentFolder != null && currentFolder.GetComponent<AutoGeneratedNextPageMarker>() != null)
                        currentFolder = currentFolder.parent;
                    return currentFolder == null ? null : currentFolder.gameObject;
                }
            }

            Transform current = toggler.transform.parent;
            while (current != null)
            {
                MenuFolder folder = current.GetComponent<MenuFolder>();
                if (folder != null)
                {
                    if (current.GetComponent<AutoGeneratedNextPageMarker>() != null)
                    {
                        current = current.parent;
                        continue;
                    }

                    return current.gameObject;
                }

                current = current.parent;
            }

            return null;
        }

        private GameObject FindTargetPrefabRoot(GameObject target)
        {
            if (target == null)
            {
                return null;
            }

            GameObject prefabRoot = PrefabUtility.GetNearestPrefabInstanceRoot(target);
            if (prefabRoot == null)
            {
                return null;
            }

            GameObject avatarRoot = GetAvatarRootObject();
            /*
             * Avatar全体がPrefab Instanceだった場合に
             * Avatar本体全Meshを列挙しない。
             */
            if (prefabRoot == avatarRoot)
            {
                return null;
            }

            return prefabRoot;
        }

        private GameObject GetAvatarRootObject()
        {
            if (sourceMenuFolder == null)
            {
                return null;
            }

            VRCAvatarDescriptor descriptor = sourceMenuFolder.GetComponentInParent<VRCAvatarDescriptor>();
            if (descriptor != null)
            {
                return descriptor.gameObject;
            }

            return sourceMenuFolder.transform.root.gameObject;
        }

        private static List<GameObject> ReadTargets(ItemToggler toggler)
        {
            List<GameObject> result = new List<GameObject>();
            if (toggler == null)
            {
                return result;
            }

            SerializedObject serializedObject = new SerializedObject(toggler);
            SerializedProperty objects = serializedObject.FindProperty("parameter").FindPropertyRelative("objects");
            for (int i = 0; i < objects.arraySize; i++)
            {
                GameObject target = objects.GetArrayElementAtIndex(i).FindPropertyRelative("obj").objectReferenceValue as GameObject;
                if (target != null)
                {
                    result.Add(target);
                }
            }

            return result;
        }

        private static bool ReadBoolProperty(SerializedObject serializedObject, string propertyName, bool defaultValue)
        {
            SerializedProperty property = serializedObject.FindProperty(propertyName);
            if (property == null)
            {
                return defaultValue;
            }

            return property.boolValue;
        }

        private static bool HasNonObjectParameterSettings(SerializedObject serializedObject)
        {
            SerializedProperty parameter = serializedObject.FindProperty("parameter");
            if (parameter == null)
            {
                return false;
            }

            string[] propertyNames =
            {
                "blendShapeModifiers",
                "materialReplacers",
                "materialPropertyModifiers",
                "clips"
            };
            foreach (string propertyName in propertyNames)
            {
                SerializedProperty property = parameter.FindPropertyRelative(propertyName);
                if (property != null && property.isArray && property.arraySize > 0)
                {
                    return true;
                }
            }

            return false;
        }

        private static bool HasMenuParentOverride(SerializedObject serializedObject)
        {
            var modularAvatar = serializedObject.FindProperty("parentOverrideMA");
            return modularAvatar != null && modularAvatar.objectReferenceValue != null;
        }

        private static bool CanSafelyMoveWholeToggler(ItemToggler toggler)
        {
            if (toggler == null || toggler.gameObject == null)
            {
                return false;
            }

            GameObject target = toggler.gameObject;
            if (PrefabUtility.IsPartOfPrefabInstance(target))
                return false;
            if (target.transform.childCount > 0)
            {
                return false;
            }

            Component[] components = target.GetComponents<Component>();
            foreach (Component component in components)
            {
                if (component == null)
                {
                    return false;
                }

                if (component is Transform || component == toggler)
                {
                    continue;
                }

                return false;
            }

            return true;
        }

        private static void AddLockReason(ExistingGroup group, string reason)
        {
            group.structuralLocked = true;
            if (string.IsNullOrEmpty(group.lockReason))
            {
                group.lockReason = reason;
            }
            else if (!group.lockReason.Contains(reason))
            {
                group.lockReason += "\n" + reason;
            }
        }

        private bool ContainsMenuFolder(GameObject target)
        {
            foreach (MenuFolderEntry entry in menuFolders)
            {
                if (entry.gameObject == target)
                {
                    return true;
                }
            }

            return false;
        }

        private static bool HasEditorOnlyAncestor(GameObject target)
        {
            if (target == null)
            {
                return false;
            }

            Transform current = target.transform.parent;
            while (current != null)
            {
                if (current.CompareTag("EditorOnly"))
                {
                    return true;
                }

                current = current.parent;
            }

            return false;
        }

        private static string GetRelativePath(Transform root, Transform target)
        {
            Stack<string> names = new Stack<string>();
            Transform current = target;
            while (current != null && current != root)
            {
                names.Push(current.name);
                current = current.parent;
            }

            return string.Join("/", names);
        }
    }
