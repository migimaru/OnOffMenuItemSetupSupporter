using System;
using System.Linq;
using System.Collections.Generic;
using UnityEditor;
using UnityEngine;
using VRC.SDK3.Avatars.Components;
using jp.lilxyzw.lilycalinventory.runtime;
using Migimaru.OnOffMenuItemSetupSupporter;

namespace Migimaru.OnOffMenuItemSetupSupporter.Editor
{
    public sealed partial class ItemTogglerEditWindow
    {
        private bool CompleteChanges()
        {
            if (overwriteMode && CountSelectedMeshes() == 0)
            {
                ResetChanges();
                return true;
            }

            return !HasWorkspaceChanges() || ApplyWorkspaceChanges();
        }

        private bool ApplyWorkspaceChanges()
        {
            if (sourceMenuFolder == null || (overwriteMode && CountSelectedMeshes() == 0))
                return false;
            EnsureInitialCheckpoint();
            SortEntriesByOutfit();
            bool reorder = HasOrderChanges();
            createdItems.Clear();
            var pendingView = CaptureViewState();
            var before = sceneHistory.Capture(displayEntries.Select(entry => entry.gameObject));
            foreach (var entry in displayEntries)
                if (entry.gameObject != null)
                    before.meshes[entry.gameObject] = new MenuSceneHistory.MeshState
                    {
                        active = entry.snapshotActive,
                        tag = entry.snapshotTag
                    };
            Undo.FlushUndoRecordObjects();
            applyingTransaction = true;
            Undo.IncrementCurrentGroup();
            int undoGroup = Undo.GetCurrentGroup();
            Undo.SetCurrentGroupName(overwriteMode ? "ON/OFFメニューを上書き" : "ON/OFFメニューの編集を適用");
            try
            {
                bool success = overwriteMode ? ApplyOverwrite() : ApplyEditChanges();
                if (!success)
                {
                    Undo.FlushUndoRecordObjects();
                    Undo.RevertAllDownToGroup(undoGroup);
                    RebuildFromHierarchy();
                    ApplyViewState(pendingView);
                    return false;
                }

                if (reorder) ApplyMenuOrder();
                ApplyChildFolderOrder();
                var draft = CaptureViewState();
                RebuildFromHierarchy();
                ApplyViewState(draft);
                foreach (var entry in displayEntries)
                {
                    entry.snapshotMenuFolder = entry.selectedMenuFolder;
                    InitializeObjectSnapshot(entry);
                }

                baselineView = CaptureViewState();
                var after = sceneHistory.Capture(displayEntries.Select(entry => entry.gameObject));
                checkpoints.Add(new Checkpoint { before = before, changed = sceneHistory.ChangedNodes(before, after), view = baselineView });
                return true;
            }
            catch (Exception exception)
            {
                Undo.FlushUndoRecordObjects();
                Undo.RevertAllDownToGroup(undoGroup);
                RebuildFromHierarchy();
                ApplyViewState(pendingView);
                Debug.LogException(exception);
                EditorUtility.DisplayDialog("変更を適用できません", exception.Message, "OK");
                return false;
            }
            finally
            {
                Undo.FlushUndoRecordObjects();
                Undo.CollapseUndoOperations(undoGroup);
                Undo.IncrementCurrentGroup();
                applyingTransaction = false;
                Repaint();
            }
        }

        private bool IsManagedMenuObject(GameObject target)
        {
            if (target == sourceMenuFolder)
                return true;
            var toggler = target.GetComponent<ItemToggler>();
            if (toggler != null)
                return IsLogicalFolderInScope(ResolveLogicalMenuFolder(toggler));
            var folder = target.GetComponent<MenuFolder>();
            if (folder != null && target.GetComponent<AutoGeneratedNextPageMarker>() == null)
                return IsLogicalFolderInScope(target);
            var parent = target.transform.parent;
            while (parent != null)
            {
                if (parent.GetComponent<MenuFolder>() != null && parent.GetComponent<AutoGeneratedNextPageMarker>() == null)
                    return IsLogicalFolderInScope(parent.gameObject);
                parent = parent.parent;
            }

            return false;
        }

        private bool ApplyOverwrite()
        {
            foreach (var toggler in GetRelevantItemTogglers())
                DeleteItemTogglerSafely(toggler);
            RemoveUnusedAutoPages();
            foreach (var entry in displayEntries)
                if (EffectiveFolder(entry) != null && !CreateNewSingleToggler(entry))
                    return false;
            return true;
        }

        private void RemoveUnusedAutoPages()
        {
            var destinations = new HashSet<GameObject>(displayEntries.Select(EffectiveFolder).Where(folder => folder != null));
            foreach (var folder in sourceMenuFolder.GetComponentsInChildren<MenuFolder>(true).Reverse())
            {
                if (folder.gameObject == sourceMenuFolder || folder.GetComponent<AutoGeneratedNextPageMarker>() == null ||
                    !IsManagedMenuObject(folder.gameObject) || destinations.Contains(folder.gameObject))
                    continue;
                if (folder.transform.childCount == 0 && MenuSceneHistory.IsMenuObject(folder.gameObject))
                    MenuSceneHistory.RemoveMenuObject(folder.gameObject);
            }
        }

        private void ApplyChildFolderOrder()
        {
            if (!includeChildMenuFolders)
                return;
            foreach (var folder in sourceMenuFolder.GetComponentsInChildren<MenuFolder>(true))
            {
                if (!IsManagedMenuObject(folder.gameObject))
                    continue;
                var children = folder.transform.Cast<Transform>().Where(child => child.GetComponent<MenuFolder>() != null && child.GetComponent<AutoGeneratedNextPageMarker>() == null).ToArray();
                if (children.Length == 0)
                    continue;
                Undo.RegisterFullObjectHierarchyUndo(folder.gameObject, "子MenuFolderの順序を変更");
                if (childFoldersAtTop)
                    for (int i = children.Length - 1; i >= 0; i--)
                        children[i].SetAsFirstSibling();
                else
                    foreach (var child in children)
                        child.SetAsLastSibling();
            }
        }

        private void AssignTogglerToPage(ItemToggler toggler, GameObject page)
        {
            if (CanSafelyMoveWholeToggler(toggler))
            {
                PlaceUnderPage(toggler.gameObject, page);
                var serialized = new SerializedObject(toggler);
                serialized.FindProperty("parentOverride").objectReferenceValue = null;
                serialized.ApplyModifiedProperties();
            }
            else
            {
                // Keep the object and its other components exactly where they are.
                var serialized = new SerializedObject(toggler);
                serialized.FindProperty("parentOverride").objectReferenceValue = page.GetComponent<MenuFolder>();
                serialized.ApplyModifiedProperties();
            }
        }
    }
}
