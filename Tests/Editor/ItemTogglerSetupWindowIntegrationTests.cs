        private void SetSetupMode(
            ItemTogglerSetupMode mode
        )
        {
            SetPrivateField(
                window,
                "setupMode",
                mode
            );
        }


        private void SetChildFolderPosition(
            string enumName
        )
        {
            FieldInfo field =
                typeof(ItemTogglerSetupWindow)
                    .GetField(
                        "childFolderPosition",
                        BindingFlags.Instance
                        |
                        BindingFlags.NonPublic
                    );


            Assert.IsNotNull(
                field
            );


            object enumValue =
                System.Enum.Parse(
                    field.FieldType,
                    enumName
                );


            field.SetValue(
                window,
                enumValue
            );
        }


        private static void SetPrivateField(
            object target,
            string fieldName,
            object value
        )
        {
            FieldInfo field =
                target.GetType()
                    .GetField(
                        fieldName,
                        BindingFlags.Instance
                        |
                        BindingFlags.NonPublic
                    );


            Assert.IsNotNull(
                field,
                $"Fieldが見つかりません: {fieldName}"
            );


            field.SetValue(
                target,
                value
            );
        }


        private static void InvokePrivate(
            object target,
            string methodName,
            params object[] arguments
        )
        {
            MethodInfo method =
                target.GetType()
                    .GetMethod(
                        methodName,
                        BindingFlags.Instance
                        |
                        BindingFlags.NonPublic
                    );


            Assert.IsNotNull(
                method,
                $"Methodが見つかりません: {methodName}"
            );


            method.Invoke(
                target,
                arguments
            );
        }


        private static T InvokePrivate<T>(
            object target,
            string methodName,
            params object[] arguments
        )
        {
            MethodInfo method =
                target.GetType()
                    .GetMethod(
                        methodName,
                        BindingFlags.Instance
                        |
                        BindingFlags.NonPublic
                    );


            Assert.IsNotNull(
                method,
                $"Methodが見つかりません: {methodName}"
            );


            object result =
                method.Invoke(
                    target,
                    arguments
                );


            return (T)result;
        }
    }
