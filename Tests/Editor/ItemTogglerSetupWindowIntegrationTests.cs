        private static int CountDirectItemTogglers(
            GameObject parent
        )
        {
            int count =
                0;


            foreach (
                Transform child
                in parent.transform
            )
            {
                if (
                    child.GetComponent<ItemToggler>()
                    != null
                )
                {
                    count++;
                }
            }


            return count;
        }


        private static GameObject FindDirectAutoNextPage(
            GameObject parent
        )
        {
            foreach (
                Transform child
                in parent.transform
            )
            {
                if (
                    child.GetComponent
                        <AutoGeneratedNextPageMarker>()
                    == null
                )
                {
                    continue;
                }


                if (
                    child.GetComponent<MenuFolder>()
                    == null
                )
                {
                    continue;
                }


                return child.gameObject;
            }


            return null;
        }


